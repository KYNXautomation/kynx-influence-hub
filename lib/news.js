export function formatNewsDate(date) {
  if (!date) return "";
  const [year, month, day] = date.split("-").map(Number);
  if (!month) return String(year);
  const options = day ? { month: "short", day: "numeric", year: "numeric" } : { month: "long", year: "numeric" };
  return new Intl.DateTimeFormat("en-US", options).format(new Date(Date.UTC(year, month - 1, day || 1)));
}
